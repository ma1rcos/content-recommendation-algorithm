-- 0001 — Esquema inicial do domínio.
-- Todos os timestamps são TIMESTAMPTZ (armazenados em UTC).
-- Este arquivo é aplicado uma única vez pelo runner de migrations
-- (services/recommendation-engine-python/app/migrate.py), dentro de uma transação.

CREATE TABLE categories (
    id          SMALLINT PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9_-]{1,40}$'),
    name        TEXT NOT NULL
);

CREATE TABLE tags (
    id          INTEGER PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9_-]{1,40}$')
);

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle      TEXT NOT NULL UNIQUE CHECK (char_length(handle) BETWEEN 1 AND 40),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Interesses declarados no onboarding: base do cold start de usuários novos.
CREATE TABLE user_declared_interests (
    user_id     BIGINT   NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id SMALLINT NOT NULL REFERENCES categories(id),
    PRIMARY KEY (user_id, category_id)
);

CREATE TABLE authors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT UNIQUE REFERENCES users(id) ON DELETE SET NULL,
    name        TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_blocks (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_id   BIGINT NOT NULL REFERENCES authors(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, author_id)
);

CREATE TABLE contents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT   NOT NULL REFERENCES authors(id),
    category_id  SMALLINT NOT NULL REFERENCES categories(id),
    title        TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
    status       TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'removed')),
    published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Pools por categoria/autor ordenados por recência (reconstrução do Redis).
CREATE INDEX contents_category_published_idx ON contents (category_id, published_at DESC) WHERE status = 'active';
CREATE INDEX contents_author_published_idx   ON contents (author_id, published_at DESC)   WHERE status = 'active';
CREATE INDEX contents_published_idx          ON contents (published_at DESC)              WHERE status = 'active';

CREATE TABLE content_tags (
    content_id  BIGINT  NOT NULL REFERENCES contents(id) ON DELETE CASCADE,
    tag_id      INTEGER NOT NULL REFERENCES tags(id),
    PRIMARY KEY (content_id, tag_id)
);
CREATE INDEX content_tags_tag_idx ON content_tags (tag_id, content_id);

-- Interações explícitas e visualizações. Impressões (exposição) NÃO são
-- gravadas aqui por volume: vivem apenas no Redis, com TTL.
-- event_id é a chave de idempotência: reentregas viram no-op (ON CONFLICT DO NOTHING).
CREATE TABLE interactions (
    event_id     UUID PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content_id   BIGINT NOT NULL REFERENCES contents(id) ON DELETE CASCADE,
    type         TEXT   NOT NULL CHECK (type IN ('content_viewed', 'content_liked', 'content_saved',
                                                 'content_shared', 'content_commented')),
    occurred_at  TIMESTAMPTZ NOT NULL,
    ingested_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX interactions_user_time_idx    ON interactions (user_id, occurred_at DESC);
CREATE INDEX interactions_content_idx      ON interactions (content_id);
CREATE INDEX interactions_time_idx         ON interactions (occurred_at DESC);

-- Privilégio mínimo: a role de aplicação (criada fora das migrations, ver
-- deploy/postgres/init) só lê e escreve dados; não altera o esquema.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'reco_app') THEN
        GRANT USAGE ON SCHEMA public TO reco_app;
        GRANT SELECT ON categories, tags, user_blocks TO reco_app;
        GRANT SELECT, INSERT ON user_declared_interests TO reco_app;
        GRANT SELECT, INSERT ON users, authors, contents, content_tags, interactions TO reco_app;
        GRANT UPDATE (status) ON contents TO reco_app;
        GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO reco_app;
    END IF;
END
$$;
